static bool oled_command(uint8_t command)
{
    Wire.beginTransmission(OLED_ADDR);
    Wire.write(0x00);
    Wire.write(command);
    return Wire.endTransmission() == 0;
}

bool oled_init(int sda_pin, int scl_pin, int rst_pin)
{
    Wire.begin(sda_pin, scl_pin);
    Wire.setTimeOut(50);

    const uint8_t init_commands[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6,
        0xAF
    };

    pinMode(rst_pin, OUTPUT);
    digitalWrite(rst_pin, LOW);
    delay(20);
    digitalWrite(rst_pin, HIGH);
    delay(20);

    for (uint8_t command : init_commands) {
        if (!oled_command(command)) {
            return false;
        }
    }
    return true;
}

void oled_clear()
{
    memset(screen_buffer, 0, sizeof(screen_buffer));
}

void oled_set_pixel(int x, int y, bool on)
{
    if (x < 0 || x >= OLED_SCREEN_WIDTH || y < 0 || y >= OLED_SCREEN_HEIGHT) {
        return;
    }

    int index = x + (y / 8) * OLED_SCREEN_WIDTH;
    uint8_t mask = 1 << (y % 8);
    if (on) {
        screen_buffer[index] |= mask;
    } else {
        screen_buffer[index] &= ~mask;
    }
}

void oled_draw_line(int x0, int y0, int x1, int y1, bool on)
{
    int dx = abs(x1 - x0);
    int sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0);
    int sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;

    while (true) {
        oled_set_pixel(x0, y0, on);
        if (x0 == x1 && y0 == y1) {
            break;
        }
        int e2 = 2 * err;
        if (e2 >= dy) {
            err += dy;
            x0 += sx;
        }
        if (e2 <= dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void oled_draw_rect(int x, int y, int width, int height, bool on)
{
    if (width <= 0 || height <= 0) {
        return;
    }
    oled_draw_line(x, y, x + width - 1, y, on);
    oled_draw_line(x, y, x, y + height - 1, on);
    oled_draw_line(x + width - 1, y, x + width - 1, y + height - 1, on);
    oled_draw_line(x, y + height - 1, x + width - 1, y + height - 1, on);
}

void oled_fill_rect(int x, int y, int width, int height, bool on)
{
    for (int yy = y; yy < y + height; yy++) {
        for (int xx = x; xx < x + width; xx++) {
            oled_set_pixel(xx, yy, on);
        }
    }
}

void oled_draw_char(int x, int y, char c, bool on, int scale)
{
    if (c < 32 || c > 127 || scale < 1) {
        return;
    }

    const uint8_t *glyph = FONT_5X7[c - 32];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (bits & (1 << row)) {
                oled_fill_rect(x + col * scale, y + row * scale, scale, scale, on);
            }
        }
    }
}

void oled_draw_text(int x, int y, const char *text, bool on, int scale)
{
    int cursor_x = x;
    int cursor_y = y;
    int advance = 6 * scale;

    while (*text) {
        if (*text == '\n') {
            cursor_x = x;
            cursor_y += 8 * scale;
        } else {
            oled_draw_char(cursor_x, cursor_y, *text, on, scale);
            cursor_x += advance;
        }
        text++;
    }
}

void oled_flush()
{
    oled_command(0x21);
    oled_command(0);
    oled_command(127);
    oled_command(0x22);
    oled_command(0);
    oled_command(7);

    for (int offset = 0; offset < (int)sizeof(screen_buffer); offset += 16) {
        Wire.beginTransmission(OLED_ADDR);
        Wire.write(0x40);
        for (int i = 0; i < 16; i++) {
            Wire.write(screen_buffer[offset + i]);
        }
        Wire.endTransmission();
    }
}
